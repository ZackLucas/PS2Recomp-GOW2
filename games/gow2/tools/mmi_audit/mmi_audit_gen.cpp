// MMI audit, step 1: pass every MMI instruction word through the real R5900Decoder + CodeGenerator
// and write the emitted C++ as one function per instruction (mmi_audit_check.cpp includes it).
// Optionally counts how often each MMI instruction appears in the executable segments of an ELF.
//
// usage: mmi_audit_gen <out.inc> [game.elf]
#include "ps2recomp/code_generator.h"
#include "ps2recomp/r5900_decoder.h"
#include "mmi_ops.h"

#include <cstdio>
#include <cstring>
#include <fstream>
#include <map>
#include <string>
#include <vector>

using namespace ps2recomp;

static bool isGroup(uint8_t func)
{
    return func == 0x08 || func == 0x28 || func == 0x09 || func == 0x29 || func == 0x30 || func == 0x31;
}

static const char *classify(uint32_t w)
{
    if ((w >> 26) != 0x1C)
        return nullptr;
    const uint8_t func = w & 0x3F, sa = (w >> 6) & 0x1F;
    for (const MmiOp &op : kMmiOps)
        if (op.func == func && (!isGroup(func) || op.sa == sa))
            return op.name;
    return "?unknown";
}

static void countElf(const char *path)
{
    std::ifstream f(path, std::ios::binary);
    std::vector<uint8_t> elf((std::istreambuf_iterator<char>(f)), {});
    if (elf.size() < 52 || memcmp(elf.data(), "\x7f" "ELF", 4) != 0)
    {
        fprintf(stderr, "not an ELF: %s\n", path);
        return;
    }
    auto rd32 = [&](size_t o) { uint32_t v; memcpy(&v, &elf[o], 4); return v; };
    auto rd16 = [&](size_t o) { uint16_t v; memcpy(&v, &elf[o], 2); return v; };
    const uint32_t phoff = rd32(28);
    const uint16_t phentsize = rd16(42), phnum = rd16(44);
    std::map<std::string, unsigned> counts;
    unsigned total = 0;
    for (unsigned i = 0; i < phnum; ++i)
    {
        const size_t ph = phoff + size_t(i) * phentsize;
        if (rd32(ph) != 1 /*PT_LOAD*/ || !(rd32(ph + 24) & 1) /*PF_X*/)
            continue;
        const uint32_t off = rd32(ph + 4), filesz = rd32(ph + 16);
        for (uint32_t o = off; o + 4 <= off + filesz && o + 4 <= elf.size(); o += 4)
            if (const char *n = classify(rd32(o)))
            {
                std::string name = n;
                if (name.rfind("PS", 0) == 0 && name.find('_') != std::string::npos && name.rfind("PMFHL", 0) != 0 &&
                    name.rfind("PMTHL", 0) != 0)
                    name = name.substr(0, name.find('_')); // PSLLH_5 -> PSLLH
                ++counts[name];
                ++total;
            }
    }
    printf("== MMI words in executable segments of %s: %u\n", path, total);
    for (auto &[n, c] : counts)
        printf("  %-10s %6u\n", n.c_str(), c);
}

int main(int argc, char **argv)
{
    if (argc < 2)
    {
        fprintf(stderr, "usage: %s <out.inc> [game.elf]\n", argv[0]);
        return 1;
    }
    R5900Decoder decoder;
    CodeGenerator gen({}, {});
    std::ofstream out(argv[1]);
    out << "// generated by mmi_audit_gen from the real decoder + code generator\n";
    for (const MmiOp &op : kMmiOps)
    {
        const uint32_t raw = mmiEncode(op);
        Instruction inst = decoder.decodeInstruction(0x100000, raw);
        std::string code = gen.translateInstruction(inst);
        out << "// " << op.name << " raw=0x" << std::hex << raw << std::dec << "\n";
        out << "static void gen_" << op.name << "(R5900Context *ctx) {\n" << code << "\n}\n";
    }
    out << "#define MMI_GEN_TABLE \\\n";
    for (const MmiOp &op : kMmiOps)
        out << "    {\"" << op.name << "\", gen_" << op.name << "}, \\\n";
    out << "\n";
    printf("wrote %zu generated MMI functions to %s\n", sizeof(kMmiOps) / sizeof(kMmiOps[0]), argv[1]);
    if (argc > 2)
        countElf(argv[2]);
    return 0;
}
