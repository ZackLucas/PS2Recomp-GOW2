#!/usr/bin/env python3
"""Generate games/gow2/tools/shaders/gs_vram_tables.glsl from the runtime's GS memory tables.

The C++ tables in ps2xRuntime/src/lib/gs/ps2_gs_memory.cpp are the source of truth (they are
exercised by the runtime tests); the GLSL copy is generated, never hand-edited.
"""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[3]
src = (root / "ps2xRuntime/src/lib/gs/ps2_gs_memory.cpp").read_text()
want = {  # name -> expected element count
    "BlockTableC32": 32, "BlockTableZ32": 32, "BlockTableC16": 32, "BlockTableC16S": 32,
    "BlockTableZ16": 32, "BlockTableZ16S": 32, "BlockTableP8": 32, "BlockTableP4": 32,
    "ColumnTable32": 64, "ColumnTable16": 128, "ColumnTable8": 256, "ColumnTable4": 512,
}
glsl = ["// GENERATED by games/gow2/scripts/gen_gs_tables_glsl.py from ps2_gs_memory.cpp. Do not edit.\n",
        "// The tables live in a read-only buffer (binding 15): as shader constants they were copied to\n",
        "// local memory on every inlined call and exhausted the register file on NVIDIA.\n",
        "layout(std430, binding = 15) readonly buffer GsVramTables { uint gsTables[]; };\n"]
data = []
for name, count in want.items():
    m = re.search(r"static constexpr \w+\s+" + name + r"\s*\{\{(.*?)\}\};", src, re.S)
    if not m:
        sys.exit(f"table {name} not found")
    nums = [int(n) for n in re.findall(r"\d+", m.group(1))]
    if len(nums) != count:
        sys.exit(f"table {name}: expected {count} entries, got {len(nums)}")
    glsl.append(f"const uint GS_OFF_{name} = {len(data)}u;\n")
    data.extend(nums)
dst = root / "games/gow2/tools/shaders/gs_vram_tables.glsl"
dst.write_text("".join(glsl))
hdr = root / "games/gow2/tools/gs_vram_tables.h"
hdr.write_text("// GENERATED by games/gow2/scripts/gen_gs_tables_glsl.py. Do not edit.\n#pragma once\n#include <cstdint>\n"
               f"static const uint32_t kGsVramTables[{len(data)}] = {{" + ", ".join(map(str, data)) + "};\n")
print(f"wrote {dst} and {hdr} ({len(want)} tables, {len(data)} entries)")
